-- Momo v3.46 — Support-assisted Knowledge Base drafting
-- Run in Supabase SQL Editor, then reindex Momo Support knowledge from
-- Admin > Support > Knowledge Base > Reindexar documentação.
-- Idempotent: refreshes the existing Knowledge Base help entry and adds a
-- dedicated drafting/review entry if it does not exist.

update public.knowledge_entries
set
  category = 'Knowledge Base',
  title = 'Managing the Knowledge Base',
  content = 'The Knowledge Base is managed by an organization Owner. In Portal > Knowledge Base, an Owner can add manual knowledge with Title, Category and Content, choose Public or Internal visibility, choose Published or Draft status, and save the entry. A public published manual entry is embedded/indexed when it is saved, so Reindex is not mandatory after every manual entry; Reindex is available to refresh public published knowledge after broader changes. Website knowledge can also be generated by analysing the organization public website. Running website analysis again replaces website-sourced entries while preserving manual entries. Before saving new manual business information, Momo Support should recommend that the client paste the raw information into Support so it can be checked and prepared as a clear Knowledge Base draft. Members may prepare wording with Support but cannot change the Knowledge Base themselves.',
  visibility = 'public',
  status = 'published',
  embedding = null,
  updated_at = now()
where agent_key = 'momo-support'
  and slug = 'momo-support-knowledge-base';

