-- Run after the existing knowledge base migrations and v2.7-portal-support.sql.

create or replace function public.match_portal_support_knowledge(
  query_embedding extensions.vector(1536),
  match_threshold double precision default 0.34,
  match_count integer default 6
)
returns table (
  id uuid,
  category text,
  title text,
  content text,
  similarity double precision
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select
    ke.id,
    ke.category,
    ke.title,
    ke.content,
    1 - (ke.embedding <=> query_embedding) as similarity
  from public.knowledge_entries ke
  where ke.agent_key = 'momo-support'
    and ke.visibility = 'public'
    and ke.status = 'published'
    and ke.embedding is not null
    and 1 - (ke.embedding <=> query_embedding) >= match_threshold
  order by ke.embedding <=> query_embedding
  limit greatest(1, least(match_count, 12));
$$;

revoke all on function public.match_portal_support_knowledge(extensions.vector, double precision, integer) from public;
grant execute on function public.match_portal_support_knowledge(extensions.vector, double precision, integer) to service_role;

